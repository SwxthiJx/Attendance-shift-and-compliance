@router.get("/ground-truth/compare")
def compare_ground_truth(
    pay_period_id: str = Query("PERIOD_2026_08_A", description="Pay Period ID to validate"),
    seed: int = Query(42, description="Random seed used during generation"),
    db: Session = Depends(get_db)
) -> Dict[str, Any]:
    """
    Ground-Truth Validation Endpoint:
    Compares computed DB results against the known ground-truth dataset.
    Returns matching statistics and detailed discrepancy reports.
    """
    generator = SyntheticDataGenerator(seed=seed)
    gen_data = generator.generate()
    ground_truth = gen_data["ground_truth"]

    results = db.query(PayableResult).options(
        joinedload(PayableResult.exceptions),
        joinedload(PayableResult.flags)
    ).filter(PayableResult.pay_period_id == pay_period_id).all()

    if not results:
        raise HTTPException(
            status_code=404, 
            detail=f"No processed results found for pay_period_id '{pay_period_id}'. Please run process endpoint first."
        )

    total_scenarios = len(ground_truth)
    matched_scenarios = 0
    discrepancies = []

    for (worker_id, w_date), gt_expected in ground_truth.items():
        computed_res = next((r for r in results if r.worker_id == worker_id and r.work_date == w_date), None)
        
        if not computed_res:
            discrepancies.append({
                "worker_id": worker_id,
                "work_date": str(w_date),
                "error": "Missing computed result in database"
            })
            continue

        comp_exceptions = [e.code for e in computed_res.exceptions]
        comp_flags = [f.rule_code for f in computed_res.flags]
        payable_diff = abs(computed_res.payable_hours - gt_expected["payable_hours"])

        exceptions_match = set(comp_exceptions) == set(gt_expected["exceptions"])
        flags_match = set(comp_flags) == set(gt_expected["flags"])
        hours_match = payable_diff < 0.01

        if exceptions_match and flags_match and hours_match:
            matched_scenarios += 1
        else:
            discrepancies.append({
                "worker_id": worker_id,
                "work_date": str(w_date),
                "expected": gt_expected,
                "actual": {
                    "payable_hours": computed_res.payable_hours,
                    "exceptions": comp_exceptions,
                    "flags": comp_flags
                }
            })

    accuracy_pct = round((matched_scenarios / total_scenarios) * 100.0, 2) if total_scenarios > 0 else 0.0

    return {
        "pay_period_id": pay_period_id,
        "seed": seed,
        "total_scenarios": total_scenarios,
        "matched_scenarios": matched_scenarios,
        "accuracy_percentage": accuracy_pct,
        "is_perfect_match": matched_scenarios == total_scenarios,
        "discrepancies": discrepancies
    }
