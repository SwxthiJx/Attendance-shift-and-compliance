from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session, joinedload
from typing import List, Optional, Dict, Any
from app.db.session import get_db
from app.models.result import PayableResult
from app.models.exception import ExceptionRecord
from app.models.flag import ComplianceFlag
from app.schemas.result import PayableResultResponse
from app.schemas.exception import ExceptionResponse, ComplianceFlagResponse
from app.services.generator import SyntheticDataGenerator

router = APIRouter(tags=["Results & Compliance Exceptions"])

@router.get("/results", response_model=List[PayableResultResponse])
def get_payable_results(
    pay_period_id: Optional[str] = Query(None, description="Filter by Pay Period ID"),
    worker_id: Optional[int] = Query(None, description="Filter by Worker ID"),
    db: Session = Depends(get_db)
):
    """Retrieve computed payable results per worker and work date."""
    query = db.query(PayableResult).options(
        joinedload(PayableResult.exceptions),
        joinedload(PayableResult.flags)
    )
    if pay_period_id:
        query = query.filter(PayableResult.pay_period_id == pay_period_id)
    if worker_id:
        query = query.filter(PayableResult.worker_id == worker_id)
    
    return query.order_by(PayableResult.worker_id, PayableResult.work_date).all()

@router.get("/results/{worker_id}", response_model=List[PayableResultResponse])
def get_payable_results_for_worker(
    worker_id: int,
    pay_period_id: Optional[str] = Query(None, description="Filter by Pay Period ID"),
    db: Session = Depends(get_db)
):
    """Retrieve computed payable results for a specific worker."""
    query = db.query(PayableResult).options(
        joinedload(PayableResult.exceptions),
        joinedload(PayableResult.flags)
    ).filter(PayableResult.worker_id == worker_id)
    
    if pay_period_id:
        query = query.filter(PayableResult.pay_period_id == pay_period_id)
        
    results = query.order_by(PayableResult.work_date).all()
    if not results:
        raise HTTPException(status_code=404, detail=f"No results found for worker_id {worker_id}")
    return results

@router.get("/exceptions", response_model=List[ExceptionResponse])
def get_exceptions(
    pay_period_id: Optional[str] = Query(None, description="Filter by Pay Period ID"),
    worker_id: Optional[int] = Query(None, description="Filter by Worker ID"),
    code: Optional[str] = Query(None, description="Filter by Exception Code"),
    db: Session = Depends(get_db)
):
    """Retrieve operational exceptions requiring administrative review."""
    query = db.query(ExceptionRecord)
    if pay_period_id:
        query = query.filter(ExceptionRecord.pay_period_id == pay_period_id)
    if worker_id:
        query = query.filter(ExceptionRecord.worker_id == worker_id)
    if code:
        query = query.filter(ExceptionRecord.code == code)

    return query.order_by(ExceptionRecord.worker_id, ExceptionRecord.work_date).all()

